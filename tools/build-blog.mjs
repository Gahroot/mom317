function keywords(d) {
  const words = new Set();
  for (const k of [d.primary_keyword, ...(Array.isArray(d.secondary_keywords) ? d.secondary_keywords : [])])
    for (const w of String(k || "").toLowerCase().split(/[^a-z0-9]+/)) if (w.length > 2) words.add(w);
  return words;
}

export function related(post, all, n = 3) {
  const mine = keywords(post.data);
  return all
    .filter((p) => p.data.slug !== post.data.slug)
    .map((p) => { let score = 0; for (const w of keywords(p.data)) if (mine.has(w)) score++; return { p, score }; })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score || (a.p.data.date < b.p.data.date ? 1 : a.p.data.date > b.p.data.date ? -1 : 0) || (a.p.data.slug < b.p.data.slug ? -1 : 1))
    .slice(0, n).map((x) => x.p);
}

