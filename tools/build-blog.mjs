// ---------- Build ----------
export function loadPosts(postsDir) {
  if (!existsSync(postsDir)) return { posts: [], errors: [] };
  const posts = [], errors = [];
  for (const f of readdirSync(postsDir).filter((f) => f.endsWith(".md")).sort()) {
    const file = join(postsDir, f);
    try {
      const post = parseFrontmatter(readFileSync(file, "utf8"));
      for (const e of validatePost(post, file)) errors.push(`${f}: ${e}`);
      posts.push(post);
    } catch (e) { errors.push(`${f}: ${e.message}`); }
  }
  return { posts, errors };
}

/** Returns { files: Map<relPath, content>, errors } for the given posts dir. Paths are relative to siteDir. */
export function build(postsDir) {
  const { posts, errors } = loadPosts(postsDir);
  const live = posts
    .filter((p) => p.data.status === "approved" && p.data.approved_by && !errors.some((e) => e.startsWith(p.data.slug + ".md:")))
    .sort((a, b) => (a.data.date < b.data.date ? 1 : a.data.date > b.data.date ? -1 : a.data.slug < b.data.slug ? -1 : 1));
  const files = new Map();
  for (const p of live) files.set(`blog/${p.data.slug}/index.html`, renderPost(p, live));
  files.set("blog/index.html", renderIndex(live));
  files.set("about/index.html", renderAbout());
  files.set("sitemap.xml", renderSitemap(live));
  files.set("feed.xml", renderFeed(live));
  files.set("llms.txt", renderLlms(live));
  return { files, errors };
}

/** Generated post dirs on disk that are no longer produced (e.g. a post went back to draft). */
function orphans(siteDir, files) {
  const dir = join(siteDir, "blog");
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !files.has(`blog/${e.name}/index.html`))
    .map((e) => `blog/${e.name}/index.html`)
    .filter((rel) => existsSync(join(siteDir, rel)) && readFileSync(join(siteDir, rel), "utf8").includes(GENERATED_MARK));
}

export function run({ root, check = false, postsDir, siteDir, log = console.log }) {
  postsDir = postsDir || join(root, "content/posts");
  siteDir = siteDir || join(root, "site");
  const { files, errors } = build(postsDir);
  const problems = [...errors];
  if (check) {
    for (const [rel, content] of files) {
      const p = join(siteDir, rel);
      if (!existsSync(p) || readFileSync(p, "utf8") !== content) problems.push(`stale: site/${rel} (run node tools/build-blog.mjs)`);
    }
    for (const rel of orphans(siteDir, files)) problems.push(`stale: site/${rel} is no longer published`);
  } else {
    for (const [rel, content] of files) { mkdirSync(dirname(join(siteDir, rel)), { recursive: true }); writeFileSync(join(siteDir, rel), content); }
    for (const rel of orphans(siteDir, files)) rmSync(dirname(join(siteDir, rel)), { recursive: true });
    log(`built ${files.size} files`);
  }
  for (const p of problems) log("error: " + p);
  return problems.length ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  process.exitCode = run({ root, check: process.argv.includes("--check") });
}
