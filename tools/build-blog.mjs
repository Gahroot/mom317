// ---------- Frontmatter ----------
function scalar(v) {
  v = v.replace(/\s+#\s.*$/, "").trim();
  if ((v.startsWith('"') && v.endsWith('"') && v.length > 1) || (v.startsWith("'") && v.endsWith("'") && v.length > 1)) return v.slice(1, -1);
  return v;
}

/** Parses `---` frontmatter: `key: value`, block lists of scalars, and block lists of `k: v` maps. */
export function parseFrontmatter(text) {
  const src = text.replace(/\r\n/g, "\n");
  const m = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(src);
  if (!m) throw new Error("missing frontmatter");
  const data = {};
  let key = null, item = null;
  for (const raw of m[1].split("\n")) {
    if (!raw.trim() || /^\s*#/.test(raw)) continue;
    const top = /^([A-Za-z_][\w-]*):\s*(.*)$/.exec(raw);
    if (top) {
      key = top[1]; item = null;
      const v = scalar(top[2]);
      data[key] = v === "" ? [] : v;
      continue;
    }
    const li = /^\s+-\s*(.*)$/.exec(raw);
    if (li && key) {
      if (!Array.isArray(data[key])) data[key] = [];
      const kv = /^([A-Za-z_][\w-]*):\s*(.*)$/.exec(li[1]);
      if (kv) { item = { [kv[1]]: scalar(kv[2]) }; data[key].push(item); }
      else { item = null; data[key].push(scalar(li[1])); }
      continue;
    }
    const sub = /^\s+([A-Za-z_][\w-]*):\s*(.*)$/.exec(raw);
    if (sub && item) { item[sub[1]] = scalar(sub[2]); continue; }
    throw new Error("cannot parse frontmatter line: " + raw.trim());
  }
  // An empty `key:` with no list items means empty string.
  for (const k of Object.keys(data)) if (Array.isArray(data[k]) && data[k].length === 0 && !["secondary_keywords", "faq", "sources", "claims"].includes(k)) data[k] = "";
  return { data, body: m[2] };
}

// ---------- Markdown ----------
export const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
export const slugify = (s) => String(s).toLowerCase().replace(/<[^>]+>/g, "").replace(/&[a-z]+;/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

function inline(text, ctx) {
  let s = esc(text);
  s = s.replace(/\[\^(\w+)\]/g, (_, id) => {
    ctx.cites.push(id);
    const n = (ctx.count[id] = (ctx.count[id] || 0) + 1);
    return `<sup><a href="#source-${id}" id="cite-${id}-${n}" aria-label="Source ${id}">[${id}]</a></sup>`;
  });
  s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, t, url) => {
    const ext = /^https?:/.test(url) && !url.startsWith(SITE);
    return `<a href="${url}"${ext ? ' rel="noopener"' : ""}>${t}</a>`;
  });
  s = s.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>").replace(/__([^_]+)__/g, "<strong>$1</strong>");
  s = s.replace(/(^|[^*\w])\*([^*\s][^*]*?)\*(?!\*)/g, "$1<em>$2</em>").replace(/(^|[^\w])_([^_\s][^_]*?)_(?!\w)/g, "$1<em>$2</em>");
  return s;
}

/** Renders markdown to an array of HTML blocks. Returns { blocks, headings, cites }. */
export function renderMarkdown(md) {
  const ctx = { cites: [], count: {} };
  const headings = [];
  const blocks = [];
  const lines = md.replace(/\r\n/g, "\n").split("\n");
  let i = 0;
  const used = new Set();
  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim() || /^\[\^\w+\]:/.test(line)) { i++; continue; }
    const h = /^(#{1,4})\s+(.*?)\s*#*$/.exec(line);
    if (h) {
      const level = Math.max(2, h[1].length); // the page owns the only H1
      const html = inline(h[2], ctx);
      let id = slugify(html) || "section";
      while (used.has(id)) id += "-x";
      used.add(id);
      if (level === 2) headings.push({ id, html });
      blocks.push({ type: "h" + level, html: `<h${level} id="${id}">${html}</h${level}>` });
      i++; continue;
    }
    if (/^>\s?/.test(line)) {
      const buf = [];
      while (i < lines.length && /^>\s?/.test(lines[i])) buf.push(lines[i++].replace(/^>\s?/, ""));
      blocks.push({ type: "quote", html: `<blockquote><p>${inline(buf.join(" "), ctx)}</p></blockquote>` });
      continue;
    }
    const ul = /^\s*[-*+]\s+/, ol = /^\s*\d+[.)]\s+/;
    if (ul.test(line) || ol.test(line)) {
      const re = ul.test(line) ? ul : ol;
      const tag = re === ul ? "ul" : "ol";
      const items = [];
      while (i < lines.length && lines[i].trim()) {
        if (re.test(lines[i])) items.push(lines[i].replace(re, ""));
        else if (items.length) items[items.length - 1] += " " + lines[i].trim();
        i++;
      }
      blocks.push({ type: tag, html: `<${tag}>${items.map((t) => `<li>${inline(t, ctx)}</li>`).join("")}</${tag}>` });
      continue;
    }
    const buf = [];
    while (i < lines.length && lines[i].trim() && !/^(#{1,4}\s|>|\s*[-*+]\s|\s*\d+[.)]\s)/.test(lines[i])) buf.push(lines[i++].trim());
    blocks.push({ type: "p", html: `<p>${inline(buf.join(" "), ctx)}</p>` });
  }
  return { blocks, headings, cites: ctx.cites };
}

// ---------- Validation ----------
export function validatePost(post, file) {
  const d = post.data, errs = [];
  const need = ["title", "slug", "description", "date", "updated", "status", "answer"];
  for (const k of need) if (!d[k] || typeof d[k] !== "string") errs.push(`missing ${k}`);
  if (d.slug && !SLUG_RE.test(d.slug)) errs.push("slug must be lowercase-hyphen");
  if (file && d.slug && basename(file, ".md") !== d.slug) errs.push(`slug "${d.slug}" must equal filename`);
  for (const k of ["date", "updated"]) if (d[k] && !/^\d{4}-\d{2}-\d{2}$/.test(d[k])) errs.push(`${k} must be YYYY-MM-DD`);
  if (d.status && !["draft", "approved"].includes(d.status)) errs.push("status must be draft or approved");
  if (d.status === "approved" && (!d.approved_by || typeof d.approved_by !== "string")) errs.push("approved post needs approved_by");
  const sources = Array.isArray(d.sources) ? d.sources : [];
  const ids = new Set();
  for (const s of sources) {
    if (!s || typeof s !== "object" || !s.id) { errs.push("source without id"); continue; }
    ids.add(String(s.id));
    if (!s.title) errs.push(`source ${s.id} missing title`);
    if (!s.url || !/^https?:\/\//.test(s.url)) errs.push(`source ${s.id} missing url`);
  }
  const { cites } = renderMarkdown(post.body);
  for (const c of new Set(cites)) if (!ids.has(c)) errs.push(`citation [^${c}] has no matching source`);
  for (const c of Array.isArray(d.claims) ? d.claims : []) if (c && c.source && !ids.has(String(c.source))) errs.push(`claim cites unknown source ${c.source}`);
  for (const f of Array.isArray(d.faq) ? d.faq : []) if (!f || !f.q || !f.a) errs.push("faq item needs q and a");
  return errs;
}

